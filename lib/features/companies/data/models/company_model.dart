import '../../domain/entities/company_entity.dart';

class CompanyModel extends CompanyEntity {
  const CompanyModel({
    required super.id,
    required super.ownerId,
    required super.name,
    super.nameEn,
    super.description,
    super.logoUrl,
    super.coverUrl,
    super.industry,
    super.companySize,
    super.website,
    super.email,
    super.phone,
    super.address,
    super.city,
    super.country,
    super.foundedYear,
    super.status,
    super.isFeatured,
    super.socialLinks,
    super.commercialRegisterNumber,
    super.commercialRegisterUrl,
    super.taxCertificateNumber,
    super.taxCertificateUrl,
    super.authorizationLetterUrl,
    super.verificationSubmittedAt,
    super.verificationReviewedAt,
    super.verificationReviewedBy,
    super.verificationNotes,
    super.followerCount,
    super.employeeCount,
    super.jobCount,
    required super.createdAt,
    required super.updatedAt,
  });

  factory CompanyModel.fromJson(Map<String, dynamic> json) {
    return CompanyModel(
      id: json['id'] as String,
      ownerId: json['owner_id'] as String,
      name: json['name'] as String,
      nameEn: json['name_en'] as String?,
      description: json['description'] as String?,
      logoUrl: json['logo_url'] as String?,
      coverUrl: json['cover_url'] as String?,
      industry: json['industry'] as String?,
      companySize: json['company_size'] as String?,
      website: json['website'] as String?,
      email: json['email'] as String?,
      phone: json['phone'] as String?,
      address: json['address'] as String?,
      city: json['city'] as String?,
      country: json['country'] as String? ?? 'SA',
      foundedYear: json['founded_year'] as int?,
      status: CompanyStatus.fromString(json['status'] as String? ?? 'unverified'),
      isFeatured: json['is_featured'] as bool? ?? false,
      socialLinks: (json['social_links'] as Map<String, dynamic>?) ?? {},
      commercialRegisterNumber: json['commercial_register_number'] as String?,
      commercialRegisterUrl: json['commercial_register_url'] as String?,
      taxCertificateNumber: json['tax_certificate_number'] as String?,
      taxCertificateUrl: json['tax_certificate_url'] as String?,
      authorizationLetterUrl: json['authorization_letter_url'] as String?,
      verificationSubmittedAt: json['verification_submitted_at'] != null
          ? DateTime.parse(json['verification_submitted_at'] as String)
          : null,
      verificationReviewedAt: json['verification_reviewed_at'] != null
          ? DateTime.parse(json['verification_reviewed_at'] as String)
          : null,
      verificationReviewedBy: json['verification_reviewed_by'] as String?,
      verificationNotes: json['verification_notes'] as String?,
      followerCount: json['follower_count'] as int? ?? 0,
      employeeCount: json['employee_count'] as int? ?? 0,
      jobCount: json['job_count'] as int? ?? 0,
      createdAt: DateTime.parse(json['created_at'] as String),
      updatedAt: DateTime.parse(json['updated_at'] as String),
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'owner_id': ownerId,
      'name': name,
      'name_en': nameEn,
      'description': description,
      'logo_url': logoUrl,
      'cover_url': coverUrl,
      'industry': industry,
      'company_size': companySize,
      'website': website,
      'email': email,
      'phone': phone,
      'address': address,
      'city': city,
      'country': country,
      'founded_year': foundedYear,
      'status': status.value,
      'is_featured': isFeatured,
      'social_links': socialLinks,
      'commercial_register_number': commercialRegisterNumber,
      'commercial_register_url': commercialRegisterUrl,
      'tax_certificate_number': taxCertificateNumber,
      'tax_certificate_url': taxCertificateUrl,
      'authorization_letter_url': authorizationLetterUrl,
      'verification_submitted_at': verificationSubmittedAt?.toIso8601String(),
      'verification_reviewed_at': verificationReviewedAt?.toIso8601String(),
      'verification_reviewed_by': verificationReviewedBy,
      'verification_notes': verificationNotes,
      'follower_count': followerCount,
      'employee_count': employeeCount,
      'job_count': jobCount,
      'created_at': createdAt.toIso8601String(),
      'updated_at': updatedAt.toIso8601String(),
    };
  }

  factory CompanyModel.fromEntity(CompanyEntity entity) {
    return CompanyModel(
      id: entity.id,
      ownerId: entity.ownerId,
      name: entity.name,
      nameEn: entity.nameEn,
      description: entity.description,
      logoUrl: entity.logoUrl,
      coverUrl: entity.coverUrl,
      industry: entity.industry,
      companySize: entity.companySize,
      website: entity.website,
      email: entity.email,
      phone: entity.phone,
      address: entity.address,
      city: entity.city,
      country: entity.country,
      foundedYear: entity.foundedYear,
      status: entity.status,
      isFeatured: entity.isFeatured,
      socialLinks: entity.socialLinks,
      commercialRegisterNumber: entity.commercialRegisterNumber,
      commercialRegisterUrl: entity.commercialRegisterUrl,
      taxCertificateNumber: entity.taxCertificateNumber,
      taxCertificateUrl: entity.taxCertificateUrl,
      authorizationLetterUrl: entity.authorizationLetterUrl,
      verificationSubmittedAt: entity.verificationSubmittedAt,
      verificationReviewedAt: entity.verificationReviewedAt,
      verificationReviewedBy: entity.verificationReviewedBy,
      verificationNotes: entity.verificationNotes,
      followerCount: entity.followerCount,
      employeeCount: entity.employeeCount,
      jobCount: entity.jobCount,
      createdAt: entity.createdAt,
      updatedAt: entity.updatedAt,
    );
  }
}
